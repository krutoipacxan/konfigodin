"""Разбор введённой строки на команду и аргументы."""


def parse_line(line):
    """Разделить строку по пробелам.

    Возвращает кортеж (команда, список аргументов). Для пустой строки
    команда равна None.
    """
    parts = line.split()
    if not parts:
        return None, []
    return parts[0], parts[1:]
